@pytest.fixture
def xp_root(tmp_path):
    root = tmp_path / "XP12"
    (root / "Resources" / "plugins").mkdir(parents=True)
    pack = root / "Custom Scenery" / "Airports" / "Earth nav data"
    pack.mkdir(parents=True)
    (pack / "apt.dat").write_text(APT_DAT, encoding="utf-8")
    return root


def test_airport_elevation_and_runways(xp_root):
    ground = XPlaneGround(root=xp_root)
    runways = ground.for_airport("EDDM")
    assert len(runways) == 1
    runway = runways[0]
    assert (runway.le_ident, runway.he_ident) == ("08L", "26R")
    assert runway.surface == "ASP" and runway.lighted and not runway.closed
    assert runway.source == "sim"
    assert runway.length_ft == pytest.approx(1600 * 3.28084, rel=.5)
    assert runway.width_ft == pytest.approx(45 * 3.28084, rel=.01)
    assert runway.le_displaced_ft == pytest.approx(300 * 3.28084, rel=.01)
    # No threshold heights in apt.dat: both ends inherit the field's.
    assert runway.le_elev_ft == 448 and runway.he_elev_ft == 448
    assert runway.le_heading == pytest.approx(41.5, abs=1)
    assert (runway.le_heading + 180) % 360 == runway.he_heading


def test_frequencies_as_facility_rows(xp_root):
    ground = XPlaneGround(root=xp_root)
    found = {f.position: f for f in ground.frequencies("EDDM")}
    assert set(found) == {"ATIS", "GND", "TWR", "APP"}
    assert found["ATIS"].mhz == pytest.approx(122.8)
    assert found["GND"].mhz == pytest.approx(121.8)
    assert found["TWR"].mhz == pytest.approx(119.1)
    assert "ATIS" in found["ATIS"].name
    assert ground.frequencies("LOWI") == []


def test_unknown_and_layout_still_work(xp_root):
    ground = XPlaneGround(root=xp_root)
    assert ground.available
    assert ground.for_airport("LOWI") == ()
    layout = ground.layout("EDDM")
    assert layout is not None and layout.ident == "EDDM"
    assert len(layout.stands) == 1 and layout.edges


def test_taxiway_names_are_the_designator_not_the_size(xp_root):
    """``taxiway_C S`` is taxiway S of width class C: the letter on the
    ``taxiway_`` token is the pavement's size (A-F), and the name is
    whatever follows it -- the read that said "Delta" for A Coruña's
    taxiway S. The bare ``taxiway A`` form names it A; an edge with no
    name after the class is unnamed."""
    ground = XPlaneGround(root=xp_root)
    layout = ground.layout("EDDM")
    labels = sorted({label for near in layout.edges.values()
                         for _o, _l, _r, label in near})
    assert labels == ["", "B2", "S"]


def test_no_install_means_no_answers():
    ground = XPlaneGround()
    if ground.available:            # a real install exists: can't say
        return
    assert not ground.for_airport("EDDM") and not ground.frequencies("EDDM")


def test_earth_fix_resolver(tmp_path):
    root = tmp_path / "XP12"
    (root / "Custom Data").mkdir(parents=True)
    (root / "Custom Data" / "earth_fix.dat").write_text(
        "I\n1100 Version\n48.5000 12.0000 BAXRI\n51.2500 10.5000 NOSPA\n"
        "not a fix line\n0.0000 0.0000 NULIS\n", encoding="utf-8")
    fixes = XPlaneFixes(roots=[root])
    assert fixes("baxri") == (48.5, 12.0)
    assert fixes("NOSPA") == (51.25, 10.5)
    assert fixes("NULIS") == (0.0, 0.0)
    assert fixes("NOSUCH") is None
    assert fixes("") is None
    assert XPlaneFixes(roots=[tmp_path])("BAXRI") is None
